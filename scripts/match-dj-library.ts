// Matches the owner's song list (data/dj-library.jsonl) to the uploaded songs and reports what it would fill in. READ-ONLY: it queries the database and
// writes nothing to it. It also writes data/dj-library-fill.sql (an idempotent file of UPDATEs for TrackGenre moods and years), which it never runs.
//
//   node --env-file=.env node_modules/tsx/dist/cli.mjs scripts/match-dj-library.ts
//
// To apply what it found, after reading the report (the same database local dev, previews and production all use):
//
//   npx prisma db execute --file data/dj-library-fill.sql
//
// The rules (what is matched, what is only ever filled when empty) are in src/lib/djLibrary.ts. Not part of the build or the tests.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { prisma } from "../src/lib/prisma";
import { buildLibraryIndex, fillStatement, matchLibrary, parseLibraryJsonl, planFill, type LibraryRow } from "../src/lib/djLibrary";

const LIBRARY_PATH = "data/dj-library.jsonl";
const SQL_PATH = "data/dj-library-fill.sql";

function parseArray(json: string | null | undefined): string[] {
  try {
    const v = JSON.parse(json ?? "[]");
    return Array.isArray(v) ? v.filter((x): x is string => typeof x === "string") : [];
  } catch {
    return [];
  }
}

async function main() {
  const { rows, skipped } = parseLibraryJsonl(readFileSync(LIBRARY_PATH, "utf8"));
  const index = buildLibraryIndex(rows);

  const tracks = await prisma.track.findMany({
    select: { id: true, title: true, artist: true, genreInfo: { select: { moodsJson: true, year: true } } },
  });

  const statements: string[] = [];
  const usedRowIds = new Set<string>();
  const samples: string[] = [];
  const counts = { matched: 0, noGenreRow: 0, fillMoods: 0, fillYear: 0, alreadyFull: 0, ambiguous: 0 };

  for (const track of tracks) {
    const hits = matchLibrary(track, index);
    if (hits.length === 0) continue;
    counts.matched++;
    for (const h of hits) usedRowIds.add(h.id);
    if (new Set(hits.map((h: LibraryRow) => h.title.toLowerCase() + "|" + h.artist.toLowerCase())).size > 1) counts.ambiguous++;
    if (!track.genreInfo) {
      counts.noGenreRow++;
      continue;
    }
    const fill = planFill({ moods: parseArray(track.genreInfo.moodsJson), year: track.genreInfo.year ?? null }, hits);
    const sql = fillStatement(track.id, fill);
    if (!sql) {
      counts.alreadyFull++;
      continue;
    }
    if (fill.moods) counts.fillMoods++;
    if (fill.year != null) counts.fillYear++;
    statements.push(sql);
    if (samples.length < 15) samples.push(`  ${track.title} - ${track.artist}  ->  moods ${fill.moods ? fill.moods.join("/") : "(kept)"}${fill.year != null ? `, year ${fill.year}` : ""}`);
  }

  const unmatched = rows.filter((r) => !usedRowIds.has(r.id));
  mkdirSync("data", { recursive: true });
  writeFileSync(
    SQL_PATH,
    [
      "-- Generated by scripts/match-dj-library.ts. Fills TrackGenre moods (only while empty) and year (only while missing) for songs on the owner's list.",
      "-- Idempotent: running it twice, or after a re-classify filled them, changes nothing. Contains song ids from the shared database: keep it local (data/ is git-ignored).",
      "--   npx prisma db execute --file data/dj-library-fill.sql",
      ...statements,
      "",
    ].join("\n")
  );

  console.log(`library rows: ${rows.length} (${skipped} unreadable lines skipped) | uploaded songs checked: ${tracks.length}`);
  console.log(`uploaded songs on the list: ${counts.matched} (from ${usedRowIds.size} of ${rows.length} list rows)`);
  console.log(`  would get moods: ${counts.fillMoods} | would get a year: ${counts.fillYear} | nothing to add: ${counts.alreadyFull} | no genre record yet (skipped): ${counts.noGenreRow}`);
  console.log(`  matched by more than one different list entry: ${counts.ambiguous}`);
  console.log(`list rows with no uploaded song: ${unmatched.length}`);
  console.log(`\nsamples:\n${samples.join("\n")}`);
  console.log(`\nwrote ${statements.length} UPDATE statements to ${SQL_PATH} (not run)`);
}

main()
  .catch((err) => {
    console.error(err);
    process.exitCode = 1;
  })
  .finally(() => prisma.$disconnect());
